// Regenerates the no-JS fallback card lists in index.html and work/index.html
// from data/cases.js. Run: node scripts/build-noscript.mjs
//
// Why this exists: both fallbacks used to be hand-written HTML and drifted
// out of sync with the data repeatedly (a removed case left as a dead link,
// renamed titles, missing dates) before anyone noticed, because nothing
// forced them to stay in sync. Generating them from the same source the
// rest of the site reads from makes that class of bug structurally
// impossible instead of relying on someone remembering.
//
// The ordering logic for work/index.html's list (P0 first, then most
// recent) is duplicated from js/render-work.js rather than imported —
// that module calls init() against `document` at load time, which would
// throw in Node. Keep the two in sync if the ordering rule ever changes.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { DOMAINS, CAPABILITIES, CASES } from '../data/cases.js';
import { displayLabel, displayDateRange, isNeedsInput } from '../js/matrix.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const capabilityLabel = new Map(CAPABILITIES.map((c) => [c.slug, c.label]));

function escapeHtml(str) {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function cardHtml(caseObj, hrefPrefix) {
  const dateText = displayDateRange(caseObj);
  const org = dateText ? `${displayLabel(caseObj)} · ${dateText}` : displayLabel(caseObj);
  const tags = caseObj.capabilities.map((s) => `<li>${escapeHtml(capabilityLabel.get(s))}</li>`).join('');
  return `      <a class="case-card" href="${hrefPrefix}${caseObj.slug}/">
        <p class="card-title">${escapeHtml(caseObj.title)}</p>
        <p class="card-org">${escapeHtml(org)}</p>
        <ul class="card-tags">${tags}</ul>
      </a>`;
}

function replaceBetweenMarkers(html, start, end, replacement, label) {
  const startIdx = html.indexOf(start);
  const endIdx = html.indexOf(end);
  if (startIdx === -1 || endIdx === -1) {
    throw new Error(`${label} markers not found — did the file structure change?`);
  }
  const before = html.slice(0, startIdx + start.length);
  const after = html.slice(endIdx);
  return `${before}\n${replacement}\n      ${after}`;
}

// index.html: grouped by domain, matching js/render-home.js's default view.
function buildHomeSections() {
  return DOMAINS.map((domain) => {
    const casesInDomain = CASES.filter((c) => c.domain === domain.slug);
    if (casesInDomain.length === 0) return null;
    return `      <section class="card-group">
        <h2>${escapeHtml(domain.label)}</h2>
${casesInDomain.map((c) => cardHtml(c, 'work/')).join('\n')}
      </section>`;
  }).filter(Boolean).join('\n\n');
}

// work/index.html: flat list, P0 first then most recent — must match
// js/render-work.js's orderForWork exactly.
function recencyKey(caseObj) {
  const end = isNeedsInput(caseObj.dateEnd) ? null : caseObj.dateEnd;
  const start = isNeedsInput(caseObj.dateStart) ? null : caseObj.dateStart;
  return end || start || null;
}

function orderForWork(cases) {
  return [...cases].sort((a, b) => {
    if (a.priority !== b.priority) return a.priority === 'P0' ? -1 : 1;
    const ka = recencyKey(a);
    const kb = recencyKey(b);
    if (ka === null && kb === null) return 0;
    if (ka === null) return 1;
    if (kb === null) return -1;
    return kb.localeCompare(ka);
  });
}

function buildWorkList() {
  return orderForWork(CASES).map((c) => cardHtml(c, '')).join('\n');
}

function run() {
  const homePath = join(ROOT, 'index.html');
  const homeHtml = readFileSync(homePath, 'utf8');
  const homeUpdated = replaceBetweenMarkers(
    homeHtml,
    '<!-- NOSCRIPT-CASES:START — generated by scripts/build-noscript.mjs, do not hand-edit -->',
    '<!-- NOSCRIPT-CASES:END -->',
    buildHomeSections(),
    'index.html NOSCRIPT-CASES'
  );
  writeFileSync(homePath, homeUpdated);

  const workPath = join(ROOT, 'work', 'index.html');
  const workHtml = readFileSync(workPath, 'utf8');
  const workUpdated = replaceBetweenMarkers(
    workHtml,
    '<!-- NOSCRIPT-WORK:START — generated by scripts/build-noscript.mjs, do not hand-edit -->',
    '<!-- NOSCRIPT-WORK:END -->',
    buildWorkList(),
    'work/index.html NOSCRIPT-WORK'
  );
  writeFileSync(workPath, workUpdated);

  console.log(`Regenerated no-JS fallbacks: index.html (${CASES.length} cases, grouped by domain) and work/index.html (${CASES.length} cases, P0 then recency).`);
}

run();
